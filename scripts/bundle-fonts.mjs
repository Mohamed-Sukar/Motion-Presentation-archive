/**
 * Bundles the studio's web fonts (Cairo, Inter, JetBrains Mono) into local app assets.
 *
 * Why: `index.html` used to pull these from fonts.googleapis.com. The desktop build is otherwise
 * fully offline-capable, so a missing network connection silently degraded typography (Arabic fell
 * back to Tahoma) and every launch paid for a render-blocking third-party request.
 *
 * All three families are SIL OFL 1.1, so bundling inside the installer is permitted.
 *
 * Usage: node scripts/bundle-fonts.mjs [--force]
 */

import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptDir, '..');
const fontsDir = path.join(appDir, 'src', 'ui', 'styles', 'fonts');
const cssOutPath = path.join(appDir, 'src', 'ui', 'styles', 'fonts.css');

// A modern Chrome UA is required for the Google API to serve woff2 instead of legacy ttf.
const CHROME_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) ' +
  'Chrome/122.0.0.0 Safari/537.36';

const FAMILIES = [
  'family=Cairo:wght@400;500;600;700',
  'family=Inter:wght@400;500;600;700',
  'family=JetBrains+Mono:wght@400;500;600',
];

const CSS_URL = `https://fonts.googleapis.com/css2?${FAMILIES.join('&')}&display=swap`;

const force = process.argv.includes('--force');

async function fetchWithRetry(url, attempts = 4) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': CHROME_UA } });
      if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
      return res;
    } catch (err) {
      lastError = err;
      if (attempt < attempts) {
        await new Promise((resolve) => setTimeout(resolve, 400 * attempt));
      }
    }
  }
  throw lastError;
}

function hashOf(value) {
  return createHash('sha256').update(value).digest('hex').slice(0, 16);
}

async function main() {
  console.log(`Fetching ${CSS_URL}`);
  const cssRes = await fetchWithRetry(CSS_URL);
  const css = await cssRes.text();

  if (!css.includes('fonts.gstatic.com')) {
    throw new Error('Unexpected Google Fonts response: no gstatic urls found.');
  }

  await fs.mkdir(fontsDir, { recursive: true });

  const urls = [...new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)\s]+/g) || [])];
  console.log(`Found ${urls.length} font file(s) across ${FAMILIES.length} families.`);

  const localNameByUrl = new Map();
  let downloaded = 0;
  let reused = 0;

  for (const url of urls) {
    // Keep the real extension (.woff2) and give the file a stable content-addressed name.
    const ext = path.extname(new URL(url).pathname) || '.woff2';
    const localName = `${hashOf(url)}${ext}`;
    const target = path.join(fontsDir, localName);
    localNameByUrl.set(url, localName);

    if (!force) {
      try {
        const stat = await fs.stat(target);
        if (stat.size > 0) {
          reused++;
          continue;
        }
      } catch {
        // Not cached yet — fall through and download.
      }
    }

    const res = await fetchWithRetry(url);
    const bytes = Buffer.from(await res.arrayBuffer());
    if (bytes.length === 0) throw new Error(`Empty font file: ${url}`);
    await fs.writeFile(target, bytes);
    downloaded++;
  }

  const localCss = css.replace(/https:\/\/fonts\.gstatic\.com\/[^)\s]+/g, (url) => {
    const localName = localNameByUrl.get(url);
    if (!localName) throw new Error(`Unmapped font url: ${url}`);
    return `./fonts/${localName}`;
  });

  const banner = [
    '/* AUTO-GENERATED by scripts/bundle-fonts.mjs — do not edit by hand.',
    ' * Local copies of Cairo, Inter and JetBrains Mono (SIL OFL 1.1).',
    ' * Re-run `node scripts/bundle-fonts.mjs` to refresh from Google Fonts.',
    ' */',
    '',
  ].join('\n');

  await fs.writeFile(cssOutPath, banner + localCss, 'utf8');

  const totalBytes = (
    await Promise.all(
      [...localNameByUrl.values()].map(async (name) => {
        const stat = await fs.stat(path.join(fontsDir, name));
        return stat.size;
      })
    )
  ).reduce((sum, size) => sum + size, 0);

  console.log(`Downloaded ${downloaded}, reused ${reused}.`);
  console.log(`Wrote ${path.relative(appDir, cssOutPath)}`);
  console.log(`Total font payload: ${(totalBytes / 1024).toFixed(1)} KiB`);
}

main().catch((err) => {
  console.error('Font bundling failed:', err);
  process.exit(1);
});
